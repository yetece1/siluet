LANGUAGES = ("tr", "en")


class _Language(QObject):
    changed = Signal(str)

    def __init__(self) -> None:
        super().__init__()
        self.code = "tr"


_STATE = _Language()


def language() -> str:
    return _STATE.code


def set_language(code: str) -> None:
    if code not in LANGUAGES:
        code = "tr"
    if code != _STATE.code:
        _STATE.code = code
        _STATE.changed.emit(code)


def t(key: str, **values) -> str:
    text = STRINGS[_STATE.code].get(key) or STRINGS["tr"][key]
    return text.format(**values) if values else text
